 it('pagehide during digest clears ownership UI immediately and a remounted client cannot overlap it', async () => {
  const fetch = vi.fn().mockResolvedValueOnce(initial()).mockResolvedValueOnce(row()).mockResolvedValueOnce(initial())
  vi.stubGlobal('fetch', fetch)
  const old = await owner()
  await old.controller.prepare(fixture.source)
  const digest = deferred<ArrayBuffer>(), entered = deferred<void>()
  vi.spyOn(crypto.subtle, 'digest').mockImplementationOnce(() => { entered.resolve(); return digest.promise })
  const pending = old.controller.mount(0)
  await entered.promise
  window.dispatchEvent(new Event('pagehide'))
  expect(old.controller.state).toEqual({kind: 'disposed'})
  const fresh = await owner()
  await fresh.controller.prepare(fixture.source)
  expect(fresh.controller.state).toEqual({kind: 'unavailable', reason: 'resource'})
  expect(fetch).toHaveBeenCalledTimes(2)
  digest.resolve(Uint8Array.from(Buffer.from(fixture.rows[0]!.inputSha256, 'hex')).buffer as ArrayBuffer)
  await pending
  expect(old.controller.state).toEqual({kind: 'disposed'})
  expect(fresh.controller.state).toEqual({kind: 'unavailable', reason: 'resource'})
  expect(fetch).toHaveBeenCalledTimes(2)
  await fresh.controller.prepare(fixture.source)
  expect(fresh.controller.state.kind).toBe('ready')
 })
