 it('rapid mount generations clear old text and refuse overlap while a cancelled digest remains active', async () => {
  const fetch = vi.fn().mockResolvedValueOnce(initial()).mockResolvedValueOnce(row()).mockResolvedValueOnce(row()).mockResolvedValueOnce(row())
  vi.stubGlobal('fetch', fetch)
  const {controller} = await owner()
  await controller.prepare(fixture.source); await controller.mount(0)
  expect(controller.state).toMatchObject({kind: 'ready', mount: {kind: 'mounted', input: {text: '{}'}}})
  const digest = deferred<ArrayBuffer>(), entered = deferred<void>()
  const spy = vi.spyOn(crypto.subtle, 'digest').mockImplementationOnce(() => { entered.resolve(); return digest.promise })
  const stale = controller.mount(0)
  expect(JSON.stringify(controller.state)).not.toContain('"text"')
  await entered.promise
  const one = controller.mount(0), two = controller.mount(0), three = controller.mount(0)
  await Promise.all([one, two, three])
  expect(controller.state).toMatchObject({kind: 'ready', mount: {kind: 'unavailable', reason: 'resource'}})
  expect(JSON.stringify(controller.state)).not.toContain('"text"')
  expect(fetch).toHaveBeenCalledTimes(3); expect(spy).toHaveBeenCalledTimes(1)
  digest.resolve(Uint8Array.from(Buffer.from(fixture.rows[0]!.inputSha256, 'hex')).buffer as ArrayBuffer)
  await stale
  expect(controller.state).toMatchObject({kind: 'ready', mount: {kind: 'unavailable', reason: 'resource'}})
  expect(fetch).toHaveBeenCalledTimes(3)
  await controller.mount(0)
  expect(controller.state).toMatchObject({kind: 'ready', mount: {kind: 'mounted', input: {text: '{}'}}})
  expect(fetch).toHaveBeenCalledTimes(4)
 })
