import assert from 'node:assert/strict'
import {chromium} from 'playwright-core'
const [origin,setupCode,id]=process.argv.slice(2)
assert(origin&&setupCode&&id,'Use the disposable TestInputRecordReviewBrowser fixture')
const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox']})
const page=await browser.newPage({viewport:{width:1440,height:900},colorScheme:'dark'})
page.setDefaultTimeout(15000)
const errors=[];page.on('pageerror',error=>errors.push(error.message))
const root=origin+'/api/input-preparations/'+id
const problem='Source discovery stopped after 13 of 15 AI requests to reserve the remaining requests for saving records. Research paused at its approved request limits.'
const at=new Date().toISOString()
let run={id:'research-fixture',state:'paused',recipeVersion:1,createdAt:at,updatedAt:at,recordCount:6,sourceCount:12,unavailableSources:1,stopRequested:false,canIncrease:true,budgetRequest:{id:'request',state:'pending'},problem}
await page.route(root+'/research',route=>route.fulfill({contentType:'application/json',body:JSON.stringify({items:[run]})}))
await page.route(root+'/research/research-fixture/activity',route=>route.fulfill({contentType:'application/json',body:JSON.stringify({...run,steps:[]})}))
try {
 await page.goto(origin)
 await page.getByRole('button',{name:'Set up sign-in',exact:true}).click()
 await page.getByLabel('Owner setup code',{exact:true}).fill(setupCode)
 await page.getByRole('button',{name:'Continue',exact:true}).click()
 await page.getByRole('button',{name:'Set password',exact:true}).waitFor()
 await page.goto(origin+'/dialects/'+id)
 const controls=page.getByRole('group',{name:'Record controls',exact:true})
 const status=page.getByLabel('Research status',{exact:true})
 await status.getByText('Approval needed · 6 saved this run',{exact:true}).waitFor()
 await page.getByRole('button',{name:'Example company 7',exact:true}).waitFor()
 assert.equal(await page.getByText(problem,{exact:true}).count(),0)
 assert.equal(await page.getByText('Open a record to review its sources and AI interpretations, then save your review decision.',{exact:true}).count(),0)
 assert.equal(await status.getByText(/retained sources/).count(),0)
 await status.getByRole('button',{name:'View steps',exact:true}).click()
 const activity=page.getByRole('dialog',{name:'Research activity',exact:true})
 await activity.getByText(problem,{exact:true}).waitFor()
 await activity.getByText('12 retained sources · Record count is for this run.',{exact:true}).waitFor()
 await activity.getByText(/1 source unavailable/).waitFor()
 await activity.getByRole('button',{name:'Close',exact:true}).click()
 await page.screenshot({path:'/tmp/jps-input-status-docked.png'})
 await page.locator('.desk-pane-head').getByRole('button',{name:/^Collapse /}).click()
 // The shared toolbar owns search sizing and filter placement.
 assert.equal(await controls.getAttribute('data-collection-toolbar'),'true')
 const search=controls.locator('[data-search-field]')
 const bounds=await search.boundingBox()
 assert(Math.abs(bounds.width-368)<1,'Use the shared 23rem search width')
 const prep=await controls.getByRole('button',{name:'Preparation',exact:true}).boundingBox()
 const evaluation=await controls.getByRole('button',{name:'Evaluation',exact:true}).boundingBox()
 assert(prep.x>=bounds.x+bounds.width&&evaluation.x>prep.x)
 assert(Math.abs(prep.y-bounds.y)<2&&Math.abs(evaluation.y-bounds.y)<2,'Filters stay alongside search')
 const statusBounds=await status.boundingBox();assert(statusBounds.height<=52,'Desktop status must remain one compact row')
 await page.getByRole('checkbox',{name:'Select Example company 1',exact:true}).check()
 await controls.getByRole('button',{name:'1 selected',exact:true}).click()
 const evaluate=page.getByRole('menuitem',{name:'Evaluate…',exact:true})
 assert.equal(await evaluate.getAttribute('aria-disabled'),'true')
 const reason=page.getByText('Mark every selected AI record Ready for evaluation for the current recipe. No records were skipped.',{exact:true})
 await reason.waitFor();assert(await reason.evaluate(el=>!!el.closest('[role="menu"]')))
 await evaluate.press('Escape')
 await controls.getByRole('button',{name:'Clear selection',exact:true}).click()
 await page.screenshot({path:'/tmp/jps-input-status-dark-wide.png'})
 await controls.getByRole('searchbox',{name:'Search records',exact:true}).fill('company 1')
 assert.equal(await page.getByRole('button',{name:'Example company 7',exact:true}).count(),0)
 await controls.getByRole('button',{name:'Clear filters',exact:true}).click()
 await page.getByRole('button',{name:'Example company 7',exact:true}).waitFor()
 for(const [width,theme] of [[1000,'dark'],[390,'light']]) {
  await page.setViewportSize({width,height:900});await page.evaluate(theme=>document.documentElement.setAttribute('data-theme',theme),theme)
  const view=controls.getByRole('button',{name:'View options',exact:true});await view.waitFor()
  await view.click()
  await page.getByRole('menuitemradio',{name:'Research needs review',exact:true}).click()
  await page.keyboard.press('Escape')
  await view.click()
  await page.getByRole('menuitemradio',{name:'Not run',exact:true}).click()
  await page.keyboard.press('Escape')
  assert.equal(await view.textContent(),'View2')
  assert(await controls.evaluate(el=>el.scrollWidth<=el.clientWidth),'Toolbar must fit the pane')
  assert(await status.evaluate(el=>el.scrollWidth<=el.clientWidth),'Status and actions must fit the pane')
  await status.getByRole('button',{name:'Review increase',exact:true}).waitFor()
  await page.screenshot({path:`/tmp/jps-input-status-${theme}-${width}.png`})
  await view.click();await page.getByRole('menuitem',{name:'Clear filters',exact:true}).click()
 }
 assert.deepEqual(errors,[])
 console.log(JSON.stringify({compactStatus:true,detailsRetained:true,sharedSearchWidth:true,adjacentFilters:true,contextualEvaluationReason:true,filtersWork:true,narrowLayout:true,browserErrors:errors}))
} catch(error) {
 await page.screenshot({path:'/tmp/jps-input-status-failure.png'})
 console.error((await page.locator('body').innerText()).slice(-4000));throw error
} finally {await browser.close()}
