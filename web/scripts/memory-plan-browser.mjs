import assert from 'node:assert/strict'
import {chromium} from 'playwright-core'
const [origin,setupCode]=process.argv.slice(2)
const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox']})
const page=await browser.newPage({viewport:{width:1440,height:900},colorScheme:'dark'});page.setDefaultTimeout(20000)
const errors=[];page.on('pageerror',e=>errors.push(e.message))
async function api(path,method='GET',body,revision){const r=await fetch(origin+path,{method,headers:{Authorization:'Bearer '+setupCode,Origin:origin,'Content-Type':'application/json',...(revision?{'If-Match':revision}:{})},...(body?{body:JSON.stringify(body)}:{})});const result=await r.json();assert(r.ok,JSON.stringify(result));return result}
try{
 await page.goto(origin);await page.getByRole('button',{name:'Set up sign-in',exact:true}).click();await page.getByLabel('Owner setup code',{exact:true}).fill(setupCode);await page.getByRole('button',{name:'Continue',exact:true}).click();await page.getByRole('button',{name:'Set password',exact:true}).waitFor();await page.goto(origin)
 const composer=page.getByPlaceholder('Ask a question or describe a task…')
 await composer.fill('/plan Prepare an outreach workflow.');await composer.press('Enter')
 await page.getByText('Plan ready for review.',{exact:true}).waitFor()
 const card=page.getByRole('region',{name:'Plan',exact:true})
 await card.getByRole('button',{name:'Start work',exact:true}).waitFor()
 await page.getByRole('button',{name:'Stop',exact:true}).waitFor({state:'hidden'})
 assert.equal(await page.getByText('Approvals apply when work starts',{exact:true}).count(),1)
 await page.screenshot({path:'/tmp/jps-plan-main.png'})
 await page.waitForTimeout(1200)
 const saved=await api('/api/conversations'),chat=saved.content.chats[0]
 assert.equal(chat.interaction,'plan');assert.equal(chat.plans.length,1)
 let memory=await api('/api/ai-memory');assert.equal(memory.content.settings.use,false)
 memory=await api('/api/ai-memory','POST',{action:'save',key:'outreach-format',text:'Use concise outreach summaries.'},memory.sha256)
 await api('/api/ai-memory','POST',{action:'settings',settings:{use:true,suggest:false}},memory.sha256)
 await page.goto('about:blank')
 const linked=await api('/api/conversations');linked.content.chats[0].input={id:'list'};await api('/api/conversations','PUT',linked.content,linked.sha256)
 await page.goto(origin+'/dialects?chat='+chat.id)
 const pane=page.locator('[data-placement="pane"]')
 await pane.getByText('Prepare an outreach workflow',{exact:true}).waitFor()
 assert.equal(await pane.getByRole('combobox').first().innerText(),'Plan')
 await page.screenshot({path:'/tmp/jps-plan-pane.png'})
 await page.setViewportSize({width:900,height:850});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 await pane.getByRole('button',{name:'Start work',exact:true}).click()
 await pane.getByText('The reviewed plan is now in work mode. Further actions retain their required approvals.',{exact:true}).waitFor()
 await page.waitForTimeout(1200)
 const executed=(await api('/api/conversations')).content.chats[0]
 assert.equal(executed.interaction,'work');assert.equal(executed.plans[0].status,'started');assert(executed.plans[0].acceptedAt)
 await page.reload();await pane.getByText('Work started',{exact:true}).waitFor()
 assert.equal(await pane.getByRole('button',{name:'Start work',exact:true}).count(),0)
 // Exercise real chat provenance; API-seeding alone cannot catch checkpoint schema drift.
 memory=await api('/api/ai-memory')
 await api('/api/ai-memory','POST',{action:'settings',settings:{use:true,suggest:true}},memory.sha256)
 let input=pane.locator('textarea').last()
 await input.fill('I prefer bullet points for outreach reviews.');await input.press('Enter')
 await pane.getByText('The outreach preference is ready for memory review.',{exact:true}).waitFor()
 let pending=(await api('/api/ai-memory')).content.entries.find(e=>e.key==='outreach-review')
 assert.equal(pending?.state,'pending');assert.equal(pending.source.chatId,chat.id)
 assert(!(await api('/api/ai-memory/recall','POST',{query:'bullet outreach'})).some(e=>e.key==='outreach-review'))
 await page.waitForTimeout(800);await page.reload()
 await pane.locator('summary').filter({hasText:'Project memory'}).click()
 await pane.getByRole('button',{name:'Remember',exact:true}).click()
 await page.waitForTimeout(500)
 pending=(await api('/api/ai-memory')).content.entries.find(e=>e.key==='outreach-review');assert.equal(pending.state,'active')
 input=pane.locator('textarea').last();await input.fill('Summarize my outreach preferences.');await input.press('Enter')
 await pane.getByText('Your approved outreach preferences are available.',{exact:true}).waitFor()
 await input.fill('/remember Short introductions.');await input.press('Enter')
 await pane.getByText('Your explicit memory request has been saved.',{exact:true}).waitFor()
 assert.equal((await api('/api/ai-memory')).content.entries.find(e=>e.key==='intro-style')?.state,'active')
 assert.deepEqual(errors,[])
 console.log(JSON.stringify({mainPlan:true,panePlan:true,refresh:true,explicitStart:true,acceptancePersisted:true,approvedMemoryRecalled:true,noReplay:true,chatMemoryProvenance:true,pendingReviewSurvivesRefresh:true,reviewBeforeRecall:true,explicitRemember:true,browserErrors:errors}))
}catch(e){await page.screenshot({path:'/tmp/jps-memory-plan-failure.png'});console.error((await page.locator('body').innerText()).slice(-6000));throw e}finally{await browser.close()}
