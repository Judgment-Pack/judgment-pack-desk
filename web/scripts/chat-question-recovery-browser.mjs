import assert from 'node:assert/strict'
import {chromium} from 'playwright-core'
const [origin,setupCode]=process.argv.slice(2)
assert(origin&&setupCode,'Use the disposable Codex question fixture')
const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox']})
const page=await browser.newPage({viewport:{width:1440,height:1000},colorScheme:'dark'})
page.setDefaultTimeout(20000)
const errors=[];page.on('pageerror',error=>errors.push(error.message))
try {
 await page.goto(origin)
 await page.getByRole('button',{name:'Set up sign-in',exact:true}).click()
 await page.getByLabel('Owner setup code',{exact:true}).fill(setupCode)
 await page.getByRole('button',{name:'Continue',exact:true}).click()
 await page.getByRole('button',{name:'Set password',exact:true}).waitFor()
 for(const placement of ['main','pane']) {
  await page.goto(placement==='main'?origin:origin+'/dialects')
  const chat=page.locator(`[data-placement="${placement}"]`)
  const composer=chat.getByPlaceholder(placement==='main'?'Ask a question or describe a task…':'Ask about this dialect…')
  await composer.fill('Interview me about employee ranges. Do not start research.');await composer.press('Enter')
  const card=chat.getByRole('form',{name:'How should overlapping employee ranges be handled?',exact:true})
  await card.waitFor();await page.getByRole('button',{name:'Stop',exact:true}).waitFor({state:'hidden'})
  assert.equal(await card.locator('input:checked').count(),0)
  assert.equal(await card.getByRole('button',{name:'Submit answer',exact:true}).isDisabled(),true)
  await chat.getByText('Work · 1 step',{exact:true}).click()
  await chat.getByText('Corrected',{exact:true}).waitFor()
  assert.equal(await chat.getByText('Ask a question',{exact:true}).count(),1)
  assert.equal(await chat.getByText(/1 failed/).count(),0)
  await card.getByRole('radio',{name:'Needs review Recommended',exact:true}).check()
  await card.getByRole('textbox').fill('Check the source date')
  await page.waitForResponse(response=>response.url().endsWith('/api/conversations')&&response.request().method()==='PUT'&&response.request().postData()?.includes('Check the source date'))
  await page.reload();await card.waitFor()
  assert.equal(await card.getByRole('textbox').inputValue(),'Check the source date')
  assert(await card.getByRole('radio',{name:'Needs review Recommended',exact:true}).isChecked())
  await page.screenshot({path:`/tmp/jps-question-recovered-${placement}.png`})
  await card.getByRole('textbox').press('Enter')
  await chat.getByText('The chosen answer is saved. Research has not started.',{exact:true}).waitFor()
  assert.equal(await card.count(),0)
 }
 assert.deepEqual(errors,[])
 console.log(JSON.stringify({mainChat:true,inputsPane:true,correctedQuestion:true,optionalDescription:true,notPreselected:true,draftRestored:true,explicitAnswers:true,noResearch:true,browserErrors:errors}))
}catch(error){await page.screenshot({path:'/tmp/jps-question-recovery-failure.png'});console.error((await page.locator('body').innerText()).slice(-3500));throw error}finally{await browser.close()}
