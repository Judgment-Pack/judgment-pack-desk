import assert from 'node:assert/strict'
import {chromium} from 'playwright-core'
const [origin,setupCode,id]=process.argv.slice(2)
assert(origin&&setupCode&&id,'Use TestInputRecordReviewBrowser with disposable records')
const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox']})
const page=await browser.newPage({viewport:{width:1800,height:1000},colorScheme:'dark'})
const errors=[],writes=[]
page.setDefaultTimeout(15000)
page.on('pageerror',e=>errors.push(e.message))
page.on('request',r=>{if(r.method()==='POST'&&new URL(r.url()).pathname.endsWith('/record-reviews'))writes.push(r.postDataJSON())})
await page.route(origin+'/api/input-preparations/'+id+'/research/fixture-run',route=>route.fulfill({json:{sources:[{id:'fixture-source',url:'https://example.com/evidence',at:'2026-10-15T12:00:00Z'}],companies:[]}}))
try{
 await page.goto(origin)
 await page.getByRole('button',{name:'Set up sign-in',exact:true}).click()
 await page.getByLabel('Owner setup code',{exact:true}).fill(setupCode)
 await page.getByRole('button',{name:'Continue',exact:true}).click()
 await page.getByRole('button',{name:'Set password',exact:true}).waitFor()
 await page.goto(origin+'/dialects/'+id)
 for(const n of [1,2])await page.getByRole('checkbox',{name:'Select Example company '+n,exact:true}).check()
 await page.getByRole('button',{name:'2 selected',exact:true}).click()
 await page.getByRole('menuitem',{name:'Review research',exact:true}).click()
 const review=page.getByRole('region',{name:'Review research',exact:true})
 await review.getByRole('heading',{name:'Example company 1',exact:true}).waitFor()
 assert.equal(await page.getByRole('dialog').count(),0)
 assert(new URL(page.url()).searchParams.get('review')==='row-1,row-2')
 const table=review.getByRole('table',{name:'Research fields',exact:true})
 await table.getByRole('columnheader',{name:'Evidence',exact:true}).waitFor()
 const row=table.getByRole('row').filter({has:page.getByRole('rowheader',{name:'Location status',exact:true})})
 const cells=await row.locator('th,td').evaluateAll(cells=>cells.map(c=>{const r=c.getBoundingClientRect();return {x:r.x,y:r.y,w:r.width}}))
 assert.equal(cells.length,3);assert(cells[0].x<cells[1].x&&cells[1].x<cells[2].x);assert(Math.abs(cells[0].y-cells[2].y)<2)
 await review.getByRole('button',{name:'Details for Location status',exact:true}).click()
 await review.getByText('The office is located in Canada.',{exact:true}).waitFor()
 await page.screenshot({path:'/tmp/jps-review-workspace-dark.png'})
 const decide=async value=>{await review.getByRole('combobox',{name:'Review decision',exact:true}).click();await page.getByRole('option',{name:value,exact:true}).click()}
 await decide('Ready for evaluation');await review.getByRole('button',{name:'Add note',exact:true}).click();await review.getByRole('textbox',{name:'Review note',exact:true}).fill('First reviewed record')
 await review.getByRole('button',{name:'Next record',exact:true}).click()
 await decide('Needs more information');await review.getByRole('button',{name:'Add note',exact:true}).click();await review.getByRole('textbox',{name:'Review note',exact:true}).fill('Need employee-count evidence')
 await review.getByRole('button',{name:'Previous record',exact:true}).click()
 assert.equal(await review.getByRole('textbox',{name:'Review note',exact:true}).inputValue(),'First reviewed record');assert.equal(writes.length,0)
 await review.getByRole('button',{name:'Save and next',exact:true}).click()
 await review.getByRole('heading',{name:'Example company 2',exact:true}).waitFor()
 assert.equal(await review.getByRole('textbox',{name:'Review note',exact:true}).inputValue(),'Need employee-count evidence')
 await review.getByRole('button',{name:'Save review',exact:true}).click();await review.getByText('Review saved',{exact:true}).waitFor()
 assert.deepEqual(writes,[{recordId:'row-1',decision:'accepted',note:'First reviewed record'},{recordId:'row-2',decision:'needs-information',note:'Need employee-count evidence'}])
 await page.reload();await review.getByRole('heading',{name:'Example company 2',exact:true}).waitFor()
 assert.equal(await review.getByRole('textbox',{name:'Review note',exact:true}).inputValue(),'Need employee-count evidence')
 assert(await review.getByRole('button',{name:'Save review',exact:true}).isDisabled())
 await page.evaluate(()=>document.documentElement.setAttribute('data-theme','light'))
 await page.screenshot({path:'/tmp/jps-review-workspace-light.png'})
 await page.setViewportSize({width:390,height:844})
 await page.getByRole('button',{name:'Back to dialect',exact:true}).click()
 await review.getByRole('combobox',{name:'Record',exact:true}).waitFor()
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)
 assert.equal(overflow,false,'review must not overflow the viewport')
 const saveBox=await review.getByRole('button',{name:'Save review',exact:true}).boundingBox()
 assert(saveBox&&saveBox.y+saveBox.height<=844,'review action must stay visible')
 await page.screenshot({path:'/tmp/jps-review-workspace-mobile.png'})
 await review.getByRole('button',{name:'Back to records',exact:true}).click()
 await page.getByRole('button',{name:'Example company 1',exact:true}).click()
 await review.getByRole('heading',{name:'Example company 1',exact:true}).waitFor()
 assert.equal(await review.getByRole('button',{name:'Next record',exact:true}).count(),0)
 await page.screenshot({path:'/tmp/jps-review-single-mobile.png'})
 assert.deepEqual(errors,[])
 console.log(JSON.stringify({alignedColumns:true,scopedSaves:2,draftsRetained:true,reload:true,single:true,multiple:true,mobile:true,browserErrors:errors}))
}catch(error){await page.screenshot({path:'/tmp/jps-review-workspace-failure.png'});console.error((await page.locator('body').innerText()).slice(-3500));throw error}finally{await browser.close()}
