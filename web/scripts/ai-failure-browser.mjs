import assert from 'node:assert/strict'
import {chromium} from 'playwright-core'
const [origin,setupCode]=process.argv.slice(2)
const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox']})
const page=await browser.newPage({viewport:{width:1440,height:900},colorScheme:'dark'})
page.setDefaultTimeout(15000)
const errors=[];page.on('pageerror',e=>errors.push(e.message))
async function api(path,method='GET',body,revision){const response=await fetch(origin+path,{method,headers:{Authorization:'Bearer '+setupCode,Origin:origin,'Content-Type':'application/json',...(revision?{'If-Match':revision}:{})},...(body?{body:JSON.stringify(body)}:{})});const result=await response.json();assert(response.ok,JSON.stringify(result));return result}
try{
 await page.goto(origin)
 await page.getByRole('button',{name:'Set up sign-in',exact:true}).click()
 await page.getByLabel('Owner setup code',{exact:true}).fill(setupCode)
 await page.getByRole('button',{name:'Continue',exact:true}).click()
 await page.getByRole('button',{name:'Set password',exact:true}).waitFor()
 await page.goto(origin)
 const main=page.locator('[data-placement="main"]')
 const composer=page.getByPlaceholder('Ask a question or describe a task…')
 await composer.fill('Explain the retained work.');await composer.press('Enter')
 let recovery=main.getByRole('article',{name:'Response interrupted'})
 await recovery.waitFor()
 assert.equal(await recovery.getByRole('button',{name:'Retry response',exact:true}).isDisabled(),true)
 assert.equal(await main.getByRole('article',{name:'Response interrupted'}).count(),1)
 assert(!(await page.locator('body').innerText()).includes('PRIVATE_PROVIDER_SENTINEL'))
 await page.waitForTimeout(800)
 await page.reload()
 recovery=main.getByRole('article',{name:'Response interrupted'})
 await recovery.waitFor()
 await recovery.locator('summary').filter({hasText:'Technical details'}).click()
 await recovery.getByText('rate-limited',{exact:false}).waitFor()
 const saved=await api('/api/conversations'),chat=saved.content.chats[0]
 assert.equal(chat.checkpoint.state.failure.code,'rate-limited')
 assert.equal(chat.checkpoint.state.failure.requestId,'req_fixture')
 assert(!JSON.stringify(saved).includes('PRIVATE_PROVIDER_SENTINEL'))
 await recovery.getByRole('button',{name:'Retry response',exact:true}).click()
 await main.getByText('Recovery completed using retained work.',{exact:true}).waitFor()
 await main.getByRole('button',{name:'Stop',exact:true}).waitFor({state:'hidden'})
 await page.waitForTimeout(800)
 await page.goto('about:blank')
 const updated=await api('/api/conversations'),held=updated.content.chats.find(c=>c.id===chat.id)
 assert.equal(held.checkpoint.state.turns.filter(t=>t.role==='user').length,1)
 assert(!held.checkpoint.state.failure)
 held.inputDrafts=[{version:1,draftId:'fixture-dialect',createdAt:new Date().toISOString(),name:'Fixture dialect',intent:'Retain supplied records',target:'records',fields:[{name:'name',type:'string',description:'Supplied name'}],criteria:[],limits:{records:1,searches:0,pages:0,modelCalls:1}}]
 await api('/api/conversations','PUT',updated.content,updated.sha256)
 await page.goto(origin+'/dialects?chat='+chat.id)
 const pane=page.locator('[data-placement="pane"]')
 await pane.getByText('Explain the retained work.',{exact:true}).waitFor()
 const paneComposer=pane.locator('textarea').last()
 await paneComposer.fill('Check the current connection.');await paneComposer.press('Enter')
 recovery=pane.getByRole('article',{name:'Response interrupted'})
 await recovery.getByText('Check the AI connection settings before retrying.',{exact:true}).waitFor()
 assert.equal(await pane.getByRole('article',{name:'Response interrupted'}).count(),1)
 assert(!(await page.locator('body').innerText()).includes('PRIVATE_PROVIDER_SENTINEL'))
 await page.waitForTimeout(800)
 await page.reload()
 await pane.getByRole('article',{name:'Response interrupted'}).waitFor()
 const final=await api('/api/conversations'),state=final.content.chats.find(c=>c.id===chat.id).checkpoint.state
 assert.equal(state.failure.code,'authentication');assert.equal(state.failure.status,401)
 assert.equal(state.turns.filter(t=>t.role==='user').length,2)
 assert.deepEqual(errors,[])
 await page.screenshot({path:'/tmp/jps-ai-failure-pane.png'})
 console.log(JSON.stringify({gemini:true,main:true,pane:true,refresh:true,retryAfter:true,safeDetails:true,singleFailure:true,noDuplicateUserTurn:true,noAutomaticReplay:true,browserErrors:errors}))
}catch(error){console.error((await page.locator('body').innerText()).slice(-4000));throw error}
finally{await browser.close()}
