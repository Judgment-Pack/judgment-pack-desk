import assert from 'node:assert/strict'
import {chromium} from 'playwright-core'
const [origin,setupCode]=process.argv.slice(2)
assert(origin&&setupCode,'Use the isolated TestDelegationBrowser fixture')
const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox']})
const page=await browser.newPage({viewport:{width:1400,height:950},colorScheme:'dark'})
page.setDefaultTimeout(15000)
const errors=[],sockets=[]
page.on('pageerror',error=>errors.push(error.message))
page.on('websocket',socket=>{if(socket.url().includes('/api/agent/run'))sockets.push(socket.url())})
try {
 await page.goto(origin)
 await page.getByRole('button',{name:'Set up sign-in',exact:true}).click()
 await page.getByLabel('Owner setup code',{exact:true}).fill(setupCode)
 await page.getByRole('button',{name:'Continue',exact:true}).click()
 await page.getByRole('button',{name:'Set password',exact:true}).waitFor()
 await page.goto(origin)
 const saved=page.waitForResponse(response=>response.url().endsWith('/api/conversations')&&response.request().method()==='PUT'&&response.request().postData()?.includes('The two delegated reviews are complete.'))
 const composer=page.getByPlaceholder('Ask a question or describe a task…')
 await composer.fill('Use subagents to review the evidence and assumptions independently.')
 await composer.press('Enter')
 const work=page.getByText('Work · 2 steps',{exact:true})
 await work.waitFor();await work.click()
 const running=page.getByRole('button',{name:'Review evidence · Delegated task · Working…',exact:true})
 await running.waitFor()
 assert.equal(await running.locator('[class*="workIndicator"] svg').count(),0,'Running task replaces the chevron')
 await page.screenshot({path:'/tmp/jps-delegation-running.png'})
 await page.getByText('The two delegated reviews are complete.',{exact:true}).waitFor()
 await saved
 const completed=page.getByRole('button',{name:'Review evidence · Delegated task · Done',exact:true})
 if(!await completed.isVisible())await work.click()
 await completed.click()
 const details=page.getByRole('region',{name:'Delegated task',exact:true})
 await details.getByText('Retained child findings: the supplied context needs source review.',{exact:true}).waitFor()
 await details.getByText('List dialects',{exact:true}).waitFor()
 await page.screenshot({path:'/tmp/jps-delegation-details.png'})
 await page.reload()
 await page.getByText('The two delegated reviews are complete.',{exact:true}).waitFor()
 await page.getByText('Work · 2 steps',{exact:true}).click()
 await page.getByRole('button',{name:'Check assumptions · Delegated task · Done',exact:true}).click()
 await details.getByText('Retained child findings: the supplied context needs source review.',{exact:true}).waitFor()
 await page.evaluate(()=>document.documentElement.setAttribute('data-theme','light'))
 await page.setViewportSize({width:390,height:844})
 assert(await details.evaluate(el=>el.scrollWidth<=el.clientWidth),'Task details must fit a narrow pane')
 await page.screenshot({path:'/tmp/jps-delegation-light-narrow.png'})
 await page.setViewportSize({width:1400,height:950})
 await page.evaluate(()=>document.documentElement.setAttribute('data-theme','dark'))
 await details.press('Escape')
 await composer.fill('Please test cancellation')
 await composer.press('Enter')
 await page.getByText('Work · 1 step',{exact:true}).click()
 await page.getByRole('button',{name:'Long review · Delegated task · Working…',exact:true}).waitFor()
 const workingNotice=page.getByText('Working in this window. You can switch chats; keep this window open.',{exact:true})
 assert.equal(await workingNotice.evaluate(el=>getComputedStyle(el).textAlign),'end')
 await page.getByRole('button',{name:'Chat history',exact:true}).click()
 const history=page.getByRole('dialog',{name:'Chat history',exact:true})
 const status=history.locator('[data-running]').filter({hasText:'Working'})
 await status.waitFor();assert.equal(await status.locator('[data-spinner]').count(),1)
 const label=status.locator(':scope > span').last()
 assert.notEqual(await label.evaluate(el=>getComputedStyle(el).animationName),'none')
 await page.screenshot({path:'/tmp/jps-history-working.png'})
 await page.emulateMedia({reducedMotion:'reduce'})
 assert.equal(await label.evaluate(el=>getComputedStyle(el).animationName),'none')
 await page.emulateMedia({reducedMotion:'no-preference'})
 await history.press('Escape')
 await page.getByRole('button',{name:'Stop',exact:true}).click()
 await page.getByRole('button',{name:'Long review · Delegated task · Interrupted',exact:true}).waitFor()
 const calls=sockets.length
 await page.screenshot({path:'/tmp/jps-delegation-stopped.png'})
 await page.reload()
 await page.getByText('Please test cancellation',{exact:true}).waitFor()
 await page.getByText('Work · 1 step',{exact:true}).click()
 await page.getByRole('button',{name:'Long review · Delegated task · Interrupted',exact:true}).waitFor()
 assert.equal(sockets.length,calls,'Reload must not restart delegated work')
 assert.deepEqual(errors,[])
 console.log(JSON.stringify({exclusiveProviderHandoff:true,childCapabilityIsolation:true,sharedWorkUI:true,retainedResults:true,stopPropagates:true,reloadDoesNotRestart:true,narrowLightTheme:true,browserErrors:errors}))
} catch(error) {
 await page.screenshot({path:'/tmp/jps-delegation-failure.png'})
 console.error((await page.locator('body').innerText()).slice(-5000));throw error
} finally {await browser.close()}
