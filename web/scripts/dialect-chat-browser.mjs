import assert from 'node:assert/strict'
import {createHash} from 'node:crypto'
import {chromium} from 'playwright-core'
const [origin,setupCode]=process.argv.slice(2)
assert(origin&&setupCode,'Use the disposable pack workspace fixture')
const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox']})
const page=await browser.newPage({viewport:{width:1440,height:1000},colorScheme:'dark'})
page.setDefaultTimeout(15000)
const errors=[],modelRequests=[],mutations=[]
page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(r.method()==='POST'&&/\/api\/(codex\/run|assistant\/)/.test(r.url()))modelRequests.push(r.url());if(r.method()==='PUT'&&r.url().includes('/api/input-preparations/'))mutations.push(r.url())})
async function api(path,method='GET',body,revision){const r=await fetch(origin+path,{method,headers:{Authorization:'Bearer '+setupCode,Origin:origin,'Content-Type':'application/json',...(revision?{'If-Match':revision}:{})},...(body?{body:JSON.stringify(body)}:{})});const result=await r.json();assert(r.ok,JSON.stringify(result));return result}
try{
 await page.goto(origin)
 await page.getByRole('button',{name:'Set up sign-in',exact:true}).click()
 await page.getByLabel('Owner setup code',{exact:true}).fill(setupCode)
 await page.getByRole('button',{name:'Continue',exact:true}).click()
 await page.getByRole('button',{name:'Set password',exact:true}).waitFor()
 let saved=await api('/api/input-preparations','POST',{name:'Dialect browser fixture',recipe:{intent:'Keep original instructions'}})
 const id=saved.document.id
 saved=await api('/api/input-preparations/'+id+'/imports','POST',{kind:'csv',name:'employees.csv',content:'name,employees\nExample,60\n'},saved.sha256)
 const file=await api('/api/file?path=example.pack.json'),digest='sha256:'+createHash('sha256').update(file.content).digest('hex')
 const proposal={version:1,id:'dialect-browser-proposal',createdAt:new Date().toISOString(),inputId:id,name:saved.document.name,revision:saved.sha256,recipeVersion:saved.document.recipeVersion,kind:'update-dialect',dialect:{packKey:'example',packDigest:digest,facts:[{target:'/count',column:'employees',conversion:{kind:'decimal'}}],evidence:[],summary:'Use the employee column as a decimal. No records are changed.'}}
 const before=await api('/api/conversations')
 const chat={id:'dialect-browser-chat',title:'Create a dialect',pinned:false,archived:false,updatedAt:new Date().toISOString(),composer:'',model:'',mode:'draft',view:'chat',inputActions:[proposal]}
 await api('/api/conversations','PUT',{...before.content,chats:[...before.content.chats,chat]},before.sha256)
 await page.goto(origin+'/chats/'+chat.id)
 await page.getByRole('button',{name:'Review dialect',exact:true}).waitFor()
 await page.reload()
 await page.getByRole('button',{name:'Review dialect',exact:true}).click()
 let dialog=page.getByRole('dialog',{name:'Review dialect',exact:true})
 await dialog.getByRole('button',{name:'Save dialect',exact:true}).waitFor()
 assert(await dialog.getByRole('button',{name:'Save dialect',exact:true}).isDisabled())
 await dialog.getByRole('button',{name:'Preview conversions',exact:true}).click()
 await dialog.getByText('"60"',{exact:true}).waitFor()
 await dialog.getByRole('button',{name:'Cancel',exact:true}).click()
 assert.equal(mutations.length,0,'Preview never saves')
 // The same proposal and composer are used in the Dialects side pane.
 await page.goto(origin+'/dialects/'+id+'?tab=recipe&chat='+chat.id)
 await page.getByRole('button',{name:'Review dialect',exact:true}).click()
 dialog=page.getByRole('dialog',{name:'Review dialect',exact:true})
 await dialog.getByRole('button',{name:'Preview conversions',exact:true}).click()
 await dialog.getByText('"60"',{exact:true}).waitFor()
 await page.screenshot({path:'/tmp/jps-dialect-chat-review.png'})
 await dialog.getByRole('button',{name:'Save dialect',exact:true}).click()
 await dialog.waitFor({state:'hidden'})
 await page.getByRole('combobox',{name:'Source for count',exact:true}).waitFor()
 await page.reload()
 await page.getByRole('combobox',{name:'Use count as',exact:true}).waitFor()
 assert((await page.getByRole('combobox',{name:'Use count as',exact:true}).innerText()).includes('Decimal'))
 const after=await api('/api/input-preparations/'+id)
 assert.equal(after.document.recipe.intent,'Keep original instructions')
 assert.deepEqual(after.document.records,saved.document.records)
 assert.equal(after.document.recipe.qualification.mapping.case.facts[0].source,'/values/employees')
 assert.equal(after.document.recipe.qualification.conversions['/count'].kind,'decimal')
 const history=await api('/api/conversations')
 assert(history.content.chats.find(c=>c.id===chat.id).inputActions[0].applied)
 assert.equal(history.content.chats.filter(c=>c.id===chat.id).length,1)
 assert.equal((await api('/api/input-preparations/'+id+'/research')).items.length,0)
 assert.equal((await api('/api/input-preparations/'+id+'/evaluations')).items.length,0)
 assert.equal(await page.locator('[data-chat-composer]:visible').count(),1)
 assert.equal(await page.locator('a[href="/inputs"]').count(),0)
 assert.equal(await page.getByRole('link',{name:'Dialects',exact:true}).first().getAttribute('href'),'/dialects')
 await page.getByRole('link',{name:'Dialects',exact:true}).first().click()
 await page.getByRole('button',{name:'New dialect',exact:true}).waitFor()
 await page.screenshot({path:'/tmp/jps-dialects-workspace.png'})
 assert.equal(mutations.length,1);assert.equal(modelRequests.length,0);assert.deepEqual(errors,[])
 console.log(JSON.stringify({mainChat:true,sidePane:true,sameChatAfterReload:true,explicitPreview:true,explicitSave:true,originalRecordsPreserved:true,wireFormatUnchanged:true,dialectsNavigation:true,noRunsStarted:true,noModelRequests:true,browserErrors:errors}))
}catch(e){console.error((await page.locator('body').innerText()).slice(-5000));await page.screenshot({path:'/tmp/jps-dialect-browser-error.png'});throw e}finally{await browser.close()}
