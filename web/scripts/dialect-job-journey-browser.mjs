import assert from 'node:assert/strict'
import {chromium} from 'playwright-core'
const [origin,token,id]=process.argv.slice(2)
const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox']})
const page=await browser.newPage({viewport:{width:1500,height:1000},colorScheme:'dark'})
page.setDefaultTimeout(20000)
const errors=[];page.on('pageerror',e=>errors.push(e.message))
async function api(path){const r=await fetch(origin+path,{headers:{Authorization:'Bearer '+token}});const body=await r.json();assert(r.ok,JSON.stringify(body));return body}
async function until(read,accept){for(let i=0;i<100;i++){const v=await read();if(accept(v))return v;await new Promise(r=>setTimeout(r,150))}throw Error('Condition did not complete')}
try{
 await page.goto(origin)
 await page.getByRole('button',{name:'Set up sign-in',exact:true}).click()
 await page.getByLabel('Owner setup code',{exact:true}).fill(token)
 await page.getByRole('button',{name:'Continue',exact:true}).click()
 await page.getByRole('button',{name:'Set password',exact:true}).waitFor()
 await page.goto(origin+'/dialects/'+id)
 await page.getByRole('checkbox',{name:'Select Alex Example',exact:true}).check()
 await page.getByRole('button',{name:'1 selected',exact:true}).click()
 await page.getByRole('menuitem',{name:'Add to pack tests…',exact:true}).click()
 let dialog=page.getByRole('dialog',{name:'Add cases from Dialects',exact:true})
 await dialog.getByRole('button',{name:'Review snapshots',exact:true}).click()
 await dialog.getByRole('checkbox',{name:'I reviewed the prepared facts and evidence. Existing snapshots will be skipped.',exact:true}).check()
 await dialog.getByRole('button',{name:'Add snapshots',exact:true}).click()
 await page.waitForURL('**/packs/contacts/matrix')
 let table=page.getByRole('table',{name:'Test cases',exact:true})
 await table.getByRole('link',{name:'Alex Example',exact:true}).click()
 await page.waitForURL(/\/matrix\//)
 await page.reload()
 await page.getByText('Alex Example',{exact:true}).first().waitFor()
 const store=await api('/api/pack-tests')
 const row=store.content.suites.contacts.cases.find(c=>c.name==='Alex Example')
 assert(row.inputSnapshot);assert.equal(row.row.expectedDisposition,undefined,'Source facts do not invent policy expectations')
 assert.equal(row.row.facts.contact.role,'Operations director')
 await page.goto(origin+'/jobs')
 await page.getByRole('button',{name:'Connect Dialects',exact:true}).click()
 dialog=page.getByRole('dialog',{name:'Connect Dialects to a job',exact:true})
 await dialog.getByRole('combobox',{name:'Dialects',exact:true}).click()
 await page.getByRole('option',{name:'Alex Example',exact:true}).click()
 await dialog.getByRole('button',{name:'Review records',exact:true}).click()
 dialog=page.getByRole('dialog',{name:'Review records',exact:true})
 await dialog.getByRole('button',{name:'Review evaluation',exact:true}).click()
 dialog=page.getByRole('dialog',{name:'Create Dialects subscription',exact:true})
 await dialog.getByRole('checkbox',{name:'Include existing eligible records when enabled',exact:true}).check()
 await dialog.getByRole('checkbox',{name:'I reviewed the selected inputs and this release’s test status.',exact:true}).check()
 await page.screenshot({path:'/tmp/jps-dialect-job-review.png'})
 await dialog.getByRole('button',{name:'Save paused',exact:true}).click()
 await dialog.waitFor({state:'hidden'})
 const subscriptions=await until(()=>api('/api/input-subscriptions'),v=>v.items.some(b=>b.preparationId===id&&b.jobId))
 let sub=subscriptions.items.find(b=>b.preparationId===id&&b.jobId)
 assert.equal(sub.subscription.enabled,false);assert.equal((await api('/api/input-preparations/'+id+'/evaluations')).items.find(b=>b.id===sub.id).rows.length,0)
 await page.goto(origin+'/jobs/'+sub.jobId+'?tab=triggers')
 await page.getByRole('button',{name:'Review and enable',exact:true}).click()
 dialog=page.getByRole('dialog',{name:'Enable Dialects subscription',exact:true})
 await dialog.getByRole('checkbox',{name:'I reviewed the source, dialect, eligibility and automatic execution policy.',exact:true}).check()
 await dialog.getByRole('button',{name:'Enable',exact:true}).click()
 await dialog.waitFor({state:'hidden'})
 const completed=await until(()=>api('/api/input-preparations/'+id+'/evaluations'),v=>v.items.find(b=>b.id===sub.id)?.rows.some(r=>r.state==='completed'))
 sub=completed.items.find(b=>b.id===sub.id)
 assert.equal(sub.rows.length,1)
 assert.equal(sub.rows[0].result.disposition.outcomeId,'proceed')
 await page.getByRole('button',{name:'Pause',exact:true}).first().click()
 await until(()=>api('/api/input-subscriptions'),v=>v.items.find(b=>b.id===sub.id)?.subscription.enabled===false)
 await page.goto(origin+'/jobs/'+sub.jobId+'/runs/'+sub.rows[0].runId)
 await page.getByText('proceed',{exact:true}).first().waitFor()
 await page.reload()
 await page.getByText('proceed',{exact:true}).first().waitFor()
 await page.screenshot({path:'/tmp/jps-dialect-job-result.png'})
 assert.deepEqual(errors,[])
 console.log(JSON.stringify({snapshotFromRealResearch:true,expectationsUnset:true,casePageSurvivesRefresh:true,reviewedTestedRelease:true,savedPaused:true,explicitEnable:true,realJobDecision:'proceed',pausedAfterTest:true,browserErrors:errors}))
}catch(e){console.error((await page.locator('body').innerText()).slice(-7000));await page.screenshot({path:'/tmp/jps-dialect-job-browser-error.png'});throw e}finally{await browser.close()}
