import assert from 'node:assert/strict'
import {chromium} from 'playwright-core'
const [origin,setupCode]=process.argv.slice(2)
assert(origin&&setupCode,'Use the disposable TestChatRecoveryBrowser fixture')
const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox']})
const page=await browser.newPage({viewport:{width:1440,height:900},colorScheme:'dark'})
page.setDefaultTimeout(15000)
const errors=[];page.on('pageerror',error=>errors.push(error.message))
try{
 await page.goto(origin)
 await page.getByRole('button',{name:'Set up sign-in',exact:true}).click()
 await page.getByLabel('Owner setup code',{exact:true}).fill(setupCode)
 await page.getByRole('button',{name:'Continue',exact:true}).click()
 await page.getByRole('button',{name:'Set password',exact:true}).waitFor()
 await page.goto(origin)
 const composer=page.getByPlaceholder('Ask a question or describe a task…')
 await page.getByText('Enter to send · Shift+Enter for a new line',{exact:true}).waitFor()
 let resume
 const pending=new Promise(resolve=>{resume=resolve})
 await page.route('**/api/input-preparations*',async route=>{await pending;await route.continue()})
 await composer.fill('List my inputs, then explain them.');await composer.press('Enter')
 const summary=page.locator('summary').filter({hasText:'Work · 1 step'})
 await summary.locator('[data-spinner]').waitFor()
 assert.equal(await page.locator('.desk-dirty').count(),0)
 assert.equal((await page.title()).startsWith('* '),false)
 assert.notEqual(await summary.locator('[data-spinner]').evaluate(el=>getComputedStyle(el).animationName),'none')
 await summary.click()
 await page.locator('[data-status="working"] [data-spinner]').waitFor()
 await page.screenshot({path:'/tmp/jps-recovery-working.png'})
 await page.emulateMedia({reducedMotion:'reduce'})
 assert.equal(await summary.locator('[data-spinner]').evaluate(el=>getComputedStyle(el).animationName),'none')
 await page.emulateMedia({reducedMotion:'no-preference'})
 resume()
 await page.getByRole('status').filter({hasText:'Reconnecting… · Retry 1 of 2'}).waitFor()
 await page.screenshot({path:'/tmp/jps-recovery-reconnecting.png'})
 await fetch(origin+'/test/release')
 const notice=page.getByRole('article',{name:'Response interrupted'})
 await notice.getByText('The AI connection could not recover after automatic retries. Review completed work before continuing.',{exact:true}).waitFor()
 assert.equal(await page.locator('[data-spinner]').count(),0)
 assert.equal(await page.getByRole('button',{name:'Retry response',exact:true}).count(),1)
 const retry=notice.getByRole('button',{name:'Retry response',exact:true})
 assert.equal((await retry.boundingBox()).height,28)
 await page.evaluate(()=>document.documentElement.dataset.density='compact')
 assert.equal((await retry.boundingBox()).height,24)
 await page.evaluate(()=>document.documentElement.dataset.density='comfortable')
 await retry.focus();assert(await retry.evaluate(el=>el===document.activeElement))
 const idleColor=await retry.evaluate(el=>getComputedStyle(el).backgroundColor)
 await retry.hover()
 assert.notEqual(await retry.evaluate(el=>getComputedStyle(el).backgroundColor),idleColor)
 assert.equal(await retry.evaluate(el=>getComputedStyle(el).textDecorationLine),'none')
 const inline=page.locator('button[class*="_inline_"]').first()
 if(await inline.count()){
  await inline.hover();assert.equal(await inline.evaluate(el=>getComputedStyle(el).textDecorationLine),'none')
 }
 await page.screenshot({path:'/tmp/jps-recovery-failed.png'})
 await page.waitForTimeout(1200);await page.reload();await notice.waitFor()
 for(const colorScheme of ['dark','light']){
  await page.emulateMedia({colorScheme});await page.setViewportSize({width:390,height:844})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  await page.screenshot({path:`/tmp/jps-recovery-${colorScheme}-mobile.png`})
 }
 await retry.click()
 await page.getByText('The unfinished response is complete. The earlier input list was kept.',{exact:true}).waitFor()
 assert.equal(await notice.count(),0)
 assert.deepEqual(errors,[])
 console.log(JSON.stringify({collapsedSpinner:true,activeStepSpinner:true,reducedMotion:true,retryProgress:true,exhaustedMessage:true,hoverFeedback:true,noUnderline:true,persistedFailure:true,manualRetry:true,oneToolCall:true,mobileDarkLight:true,browserErrors:errors}))
}catch(error){await page.screenshot({path:'/tmp/jps-recovery-browser-failure.png'});console.error((await page.locator('body').innerText()).slice(-6000));throw error}
finally{await browser.close()}
