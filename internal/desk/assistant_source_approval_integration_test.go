func TestAssistantSourceManagedCatalogOwnerInvalidation(t *testing.T) {
	for _, change := range []string{"stop", "restart", "policy", "bundle", "build", "dead", "inflight-owner"} {
		t.Run(change, func(t *testing.T) {
			s, token, bundle, _, done := assistantSourceManagedCatalogFixture(t)
			raw, err := s.readSetupConnectionCatalog(context.Background(), bundle)
			assistantRunMust(t, err)
			row := assistantSourceTestRow(t, assistantSourceTestView(t, s, token), "desk-website")
			if row.Status != "review-required" {
				t.Fatal("fixture observation absent")
			}
			g := s.localGateway
			switch change {
			case "stop", "restart":
				close(done)
				if change == "restart" {
					g.restart()
				} else {
					g.mu.Lock()
					g.stop()
					g.mu.Unlock()
				}
			case "policy":
				g.mu.Lock()
				g.webPolicy = "superseded"
				g.mu.Unlock()
			case "bundle":
				assistantRunMust(t, os.WriteFile(filepath.Join(bundle, executableName("adapter-web")), []byte("changed"), 0700))
			case "build":
				g.mu.Lock()
				g.pin.build = &gatewayBuild{Revision: "changed"}
				g.mu.Unlock()
			case "dead":
				close(done)
			case "inflight-owner":
				before, err := g.catalogBasis(s.assistant, bundle)
				assistantRunMust(t, err)
				g.invalidateCatalog()
				g.mu.Lock()
				g.pin = &localGatewayPin{build: g.pin.build, URL: g.pin.URL, Authority: g.pin.Authority, Signer: g.pin.Signer, documentProcessing: true}
				g.mu.Unlock()
				after, err := g.catalogBasis(s.assistant, bundle)
				assistantRunMust(t, err)
				g.retainCatalog(s.assistant, before, after, raw)
			}
			response := policyCall(s, token, "POST", "/api/assistant-source-approvals/chat-one/approve", assistantSourceApproveRequest{row.ReviewID, 1})
			if response.Code != 409 {
				t.Fatal("stale owner approved", change, response.Code, response.Body.String())
			}
			fresh := assistantSourceTestRow(t, assistantSourceTestView(t, s, token), "desk-website")
			if fresh.Status != "setup-required" {
				t.Fatal("invalidated owner observation reused", change, fresh)
			}
			g.mu.Lock()
			retained := g.catalogObservation != nil
			g.mu.Unlock()
			if retained {
				t.Fatal("owner refusal retained obsolete witness", change)
			}
			if change == "policy" {
				g.mu.Lock()
				g.webPolicy = ""
				g.mu.Unlock()
				reverted := assistantSourceTestRow(t, assistantSourceTestView(t, s, token), "desk-website")
				if reverted.Status != "setup-required" {
					t.Fatal("policy reversion resurrected prior witness", reverted)
				}
			}
		})
	}
}

