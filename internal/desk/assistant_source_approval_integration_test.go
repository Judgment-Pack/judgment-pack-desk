	row := assistantSourceTestRow(t, assistantSourceTestView(t, s, token), "desk-website")
	if row.Status != "setup-required" {
		t.Fatal("manifest invented capability")
	}
	if _, err := os.Stat(trace); !os.IsNotExist(err) {
		t.Fatal("review started catalog process", err)
	}
	setup := policyCall(s, token, "POST", "/api/connections/catalog", map[string]any{})
	if setup.Code != 200 {
		t.Fatal("explicit setup catalog", setup.Code, setup.Body.String())
	}
	if setup.Body.String() != assistantSourceCatalogFixture+"\n" {
		t.Fatal("setup complete catalog changed", setup.Body.String())
	}
