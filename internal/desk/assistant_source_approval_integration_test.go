func assistantSourceAssertHistorical(t *testing.T, name string, before, after []byte) {
	t.Helper()
	old, err := decodeAssistantSourceStorage(name, before)
	assistantRunMust(t, err)
	ledger, err := decodeAssistantSourceStorage(name, after)
	assistantRunMust(t, err)
	if len(old.Reviews) != len(ledger.Reviews) || len(old.Approvals) != len(ledger.Approvals) {
		t.Fatal("history records lost")
	}
	for i, review := range ledger.Reviews {
		if !review.Historical {
			t.Fatal("import retained live review")
		}
		review.Historical = false
		if !bytes.Equal(assistantChatJSON(review), assistantChatJSON(old.Reviews[i])) {
			t.Fatal("review scope/snapshot changed")
		}
	}
	for i, approval := range ledger.Approvals {
		if !approval.Historical {
			t.Fatal("import retained live approval")
		}
		approval.Historical = false
		if !bytes.Equal(assistantChatJSON(approval), assistantChatJSON(old.Approvals[i])) {
			t.Fatal("approval scope/snapshot changed")
		}
	}
	// Nested value bytes are retained exactly, not regenerated by the importer.
	for _, key := range []string{"reviews", "approvals"} {
		values := func(raw []byte) []json.RawMessage {
			t.Helper()
			var fields map[string]json.RawMessage
			assistantRunMust(t, json.Unmarshal(raw, &fields))
			var records []json.RawMessage
			assistantRunMust(t, json.Unmarshal(fields[key], &records))
			return records
		}
		a, b := values(before), values(after)
		for i := range a {
			var x, y map[string]json.RawMessage
			assistantRunMust(t, json.Unmarshal(a[i], &x))
			assistantRunMust(t, json.Unmarshal(b[i], &y))
			for _, field := range []string{"scope", "snapshot"} {
				if !bytes.Equal(x[field], y[field]) {
					t.Fatal("original nested bytes rewritten", key, field)
				}
			}
		}
	}
}
func TestAssistantSourceTransferHistoricalAndSameSessionFreshReview(t *testing.T) {
	for _, mode := range []string{"backup-restore", "storage-move", "project-move", "manual-relink"} {
		t.Run(mode, func(t *testing.T) {
			s, token, pending, approved, store, name, before := assistantSourceHistoricalFixture(t)
			var after []byte
			var err error
			switch mode {
			case "backup-restore", "storage-move":
				targetRoot, err := openPrivateDataRoot(filepath.Join(t.TempDir(), "private"), true)
				assistantRunMust(t, err)
				defer targetRoot.Close()
				target := &chatDataStore{root: targetRoot}
				copied := []string{}
				if mode == "storage-move" {
					err = copyChatData(t.Context(), store, target, &copied)
				} else {
					archive, err := os.CreateTemp(t.TempDir(), "source-backup-*")
					assistantRunMust(t, err)
					defer archive.Close()
					assistantRunMust(t, buildChatBackup(t.Context(), store, archive))
					err = copyChatBackup(t.Context(), archive, target, &copied)
				}
				assistantRunMust(t, err)
				after, err = readPrivateData(target.root, name, assistantRunRecordLimit)
				assistantRunMust(t, err)
				// Restore exact imported bytes into the original session's namespace.
				assistantRunMust(t, writePrivateData(store.root, name, after))
			case "project-move":
				next := filepath.Join(t.TempDir(), "next-project")
				assistantRunMust(t, linkMovedHistory(store.root, s.conversationIdentity(), next))
				after, err = readPrivateData(store.root, name, assistantRunRecordLimit)
				assistantRunMust(t, err)
			case "manual-relink":
				previous := s.projectDir
				s.projectDir = filepath.Join(t.TempDir(), "relinked-project")
				defer func() { s.projectDir = previous }()
				request := projectHistoryRequest{PreviousProject: previous}
				preview := policyCall(s, token, "POST", "/api/storage/project-history/preview", request)
				if preview.Code != 200 {
					t.Fatal("relink preview", preview.Code, preview.Body.String())
				}
				unchanged, err := readPrivateData(store.root, name, assistantRunRecordLimit)
				assistantRunMust(t, err)
				if !bytes.Equal(unchanged, before) {
					t.Fatal("relink preview mutated approval history")
				}
				var view projectHistoryPreview
				assistantRunMust(t, json.Unmarshal(preview.Body.Bytes(), &view))
				request.SourceRevision, request.BindingsRevision = view.SourceRevision, view.BindingsRevision
				relink := policyCall(s, token, "POST", "/api/storage/project-history/relink", request)
				if relink.Code != 200 {
					t.Fatal("manual relink", relink.Code, relink.Body.String())
				}
				after, err = readPrivateData(store.root, name, assistantRunRecordLimit)
				assistantRunMust(t, err)
				s.projectDir = previous
			}
			assistantSourceAssertHistorical(t, name, before, after)
			if response := policyCall(s, token, "POST", "/api/assistant-source-approvals/chat-one/approve", assistantSourceApproveRequest{pending.ReviewID, 1}); response.Code != 409 {
				t.Fatal("same-session imported review admitted", response.Code, response.Body.String())
			}
			if response := policyCall(s, token, "POST", "/api/assistant-source-approvals/chat-one/revoke", assistantSourceRevokeRequest{approved.Approval.ID, 1}); response.Code != 409 {
				t.Fatal("historical approval admitted as live", response.Code)
			}
			fresh := assistantSourceTestRow(t, assistantSourceTestView(t, s, token), "desk-research-workflow")
			if fresh.Status == "approved" || fresh.Approval != nil || fresh.ReviewID == "" || fresh.ReviewID == pending.ReviewID {
				t.Fatal("history rebound current authority", fresh)
			}
			assistantSourceTestApprove(t, s, token, fresh)
		})
	}
}
func TestAssistantSourceStorageClassificationAndClosedHistory(t *testing.T) {
	s, token, _, _, store, name, raw := assistantSourceHistoricalFixture(t)
	if !chatStorageFile(name) || !privateWorkspaceStorageFile(name) || !historyMember(name, s.conversationName()) {
		t.Fatal("source ledger outside private history owner")
	}
	assistantRunMust(t, validateStorageFile(name, raw))
	for _, invalid := range []string{strings.Replace(name, "approvals", "Approvals", 1), strings.Replace(name, ".json", ".json.extra", 1), "../" + name, "assistant-source-approvals-" + strings.Repeat("A", 64) + ".json"} {
		if chatStorageFile(invalid) || privateWorkspaceStorageFile(invalid) {
			t.Fatal("open source ledger filename", invalid)
		}
		if _, err := decodeAssistantSourceStorage(invalid, raw); err == nil {
			t.Fatal("invalid source filename admitted", invalid)
		}
	}
	foreign := assistantSourceLedgerName(strings.Repeat("b", 64))
	if validateStorageFile(foreign, raw) == nil {
		t.Fatal("foreign filename project admitted")
	}
	for _, invalid := range []string{`null`, strings.Replace(string(raw), `"version":1`, `"version":1,"Version":1`, 1), strings.Replace(string(raw), `"consumed":true`, `"consumed":true,"historical":null`, 1)} {
		if invalid == string(raw) {
			continue
		}
		if validateStorageFile(name, []byte(invalid)) == nil {
			t.Fatal("malformed historical storage admitted")
		}
	}
	request := httptest.NewRequest("GET", "/", nil)
	request.Header.Set("Authorization", "Bearer "+testToken)
	if s.authorizeAssistantSourceStorage(request) == nil || s.authorizeStoredPolicyWorkspace(request, store.root) == nil {
		t.Fatal("launch credential read private source history")
	}
	request.Header.Set("Authorization", "Bearer "+token)
	assistantRunMust(t, s.authorizeAssistantSourceStorage(request))
	assistantRunMust(t, s.authorizeStoredPolicyWorkspace(request, store.root))
}

