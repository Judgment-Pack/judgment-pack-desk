func TestAssistantSourceNewOwnerNeedsNewExactReview(t *testing.T) {
	s, token, bundle, trace, done := assistantSourceManagedCatalogFixture(t)
	_, err := s.readSetupConnectionCatalog(t.Context(), bundle)
	assistantRunMust(t, err)
	old := assistantSourceTestRow(t, assistantSourceTestView(t, s, token), "desk-website")
	assistantSourceTestApprove(t, s, token, old)
	g := s.localGateway
	g.mu.Lock()
	oldPin := g.pin
	manifest := g.launchBundleDigest
	g.mu.Unlock()
	close(done)
	g.restart()
	nextDone := make(chan struct{})
	t.Cleanup(func() {
		select {
		case <-nextDone:
		default:
			close(nextDone)
		}
	})
	g.mu.Lock()
	g.done = nextDone
	g.pin = oldPin
	g.launchBundleDigest = manifest
	g.mu.Unlock()
	missing := assistantSourceTestRow(t, assistantSourceTestView(t, s, token), "desk-website")
	if missing.Status != "setup-required" {
		t.Fatal("restart reused catalog observation", missing)
	}
	_, err = s.readSetupConnectionCatalog(t.Context(), bundle)
	assistantRunMust(t, err)
	fresh := assistantSourceTestRow(t, assistantSourceTestView(t, s, token), "desk-website")
	if fresh.Status == "approved" || fresh.ReviewID == "" || fresh.Snapshot.Configuration.CatalogOwnerDigest == old.Snapshot.Configuration.CatalogOwnerDigest {
		t.Fatal("new owner rebound previous approval", fresh)
	}
	assistantSourceTestApprove(t, s, token, fresh)
	calls, err := os.ReadFile(trace)
	assistantRunMust(t, err)
	if string(calls) != "catalog\ncatalog\n" {
		t.Fatal("review did extra catalog work", string(calls))
	}
}
